//Print these four values, one per line, without quotes around them in the code: the integer 10,
//the decimal 3.14, the boolean true and the character 'A'.

public class Q04_Values {
    public static void main(String[] args) {
        int num = 10;
        double dec = 3.14;
        boolean isActive = true;
        char ch = 'A';

        System.out.println(num);
        System.out.println(dec);
        System.out.println(isActive);
        System.out.println(ch);
    }
}

//Output
//10
//3.14
//true
//A
