//Q03 (E) - print vs println
//File: Q03_PrintVsPrintln.java
//
//Print Java is fun on one line using three print calls (one word each).
//Print the same words on three separate lines using println.

public class Q03_PrintVsPrintln {
    public static void main(String[] args) {
        System.out.print("Java ");
        System.out.print("is ");
        System.out.print("fun");
        System.out.println();
        System.out.println("Java");
        System.out.println("is");
        System.out.println("fun");
    }
}

//Output
//Java is fun
//Java
//is
//fun
