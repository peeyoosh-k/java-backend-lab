//Q08 (E) - Tab-Separated Table
//File: Q08_TabTable.java
//
//Print the following table using \t:
//
//Name	Age	City
//Aman	20	Dehradun
//Riya	21	Delhi
//Karan	19	Haridwar

public class Q08_TabTable {
    public static void main(String[] args) {
        System.out.println("Name\tAge\tCity");
        System.out.println("Aman\t20\tDehradun");
        System.out.println("Riya\t21\tDelhi");
        System.out.println("Karan\t19\tHaridwar");
    }
}

//Output
//Name	Age	City
//Aman	20	Dehradun
//Riya	21	Delhi
//Karan	19	Haridwar